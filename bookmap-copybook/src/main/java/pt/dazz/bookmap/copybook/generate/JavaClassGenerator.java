/**
 * Writes the Java classes of a model, with BookMap annotations.
 */
public final class JavaClassGenerator {

    private static final String INDENT = "    ";

    private JavaClassGenerator() {
    }

    /**
     * Gives one Java file for each class of the model, in model order.
     *
     * @param model the model
     * @param options the generate options
     * @return the Java files
     */
    public static List<JavaFile> generate(BookModel model, GenerateOptions options) {
        List<JavaFile> files = new ArrayList<>();
        Map<String, ClassModel> byName = new HashMap<>();
        model.classes().forEach(type -> byName.put(type.name(), type));
        for (ClassModel type : model.classes()) {
            files.add(JavaFile.builder(options.packageName(),
                    type(type, inItem(type, byName), model.sourceName(), options))
                .indent(INDENT).skipJavaLangImports(true).build());
        }
        for (EnumModel type : model.enums()) {
            files.add(JavaFile.builder(options.packageName(), enumType(type, model.sourceName()))
                .indent(INDENT).skipJavaLangImports(true).build());
        }
        return files;
    }

    /**
     * Writes Java files below a source directory, in package directories. Existing files are
     * replaced.
     *
     * @param files the Java files
     * @param outputDir the source directory
     * @throws IOException if a file cannot be written
     */
    public static void writeTo(List<JavaFile> files, Path outputDir) throws IOException {
        for (JavaFile file : files) {
            file.writeTo(outputDir);
        }
    }

    /**
     * Tells if a class is an item class, or a subtype of an item class. Its members get the
     * direction of the collection.
     */
    private static boolean inItem(ClassModel type, Map<String, ClassModel> byName) {
        ClassModel current = type;
        while (current.kind() == ClassKind.SUBTYPE) {
            current = byName.get(current.superclass());
        }
        return current.kind() == ClassKind.ITEM;
    }

    private static TypeSpec type(ClassModel type, boolean inItem, String sourceName,
                                 GenerateOptions options) {
        TypeSpec.Builder builder = TypeSpec.classBuilder(type.name())
            .addModifiers(Modifier.PUBLIC)
            .addJavadoc("Generated by the BookMap copybook generator from {@code $L}.\n",
                sourceName);
        if (type.kind() == ClassKind.OPERATION) {
            builder.addAnnotation(BookOperation.class);
        }
        if (type.superclass() != null) {
            builder.superclass(ClassName.get(options.packageName(), type.superclass()));
        }
        if (type.subTypes() != null) {
            AnnotationSpec.Builder subTypes = AnnotationSpec.builder(BookSubTypes.class)
                .addMember("discriminator", "$S", type.subTypes().discriminator());
            for (SubTypeEntry entry : type.subTypes().types()) {
                subTypes.addMember("value", "$L", AnnotationSpec.builder(BookSubTypes.Type.class)
                    .addMember("value", "$S", entry.value())
                    .addMember("type", "$T.class",
                        ClassName.get(options.packageName(), entry.className()))
                    .build());
            }
            builder.addAnnotation(subTypes.build());
        }
        if (options.lombok()) {
            builder.addAnnotation(lombok("Data")).addAnnotation(lombok("NoArgsConstructor"));
            if (type.kind() == ClassKind.SUBTYPE) {
                builder.addAnnotation(AnnotationSpec.builder(lombok("EqualsAndHashCode"))
                    .addMember("callSuper", "true").build());
                builder.addAnnotation(AnnotationSpec.builder(lombok("ToString"))
                    .addMember("callSuper", "true").build());
            }
        }
        for (MemberModel member : type.members()) {
            TypeName javaType = javaType(member, options.packageName());
            FieldSpec.Builder field = FieldSpec.builder(javaType, member.name(),
                    Modifier.PRIVATE)
                .addJavadoc(declaration(member.declaration()))
                .addAnnotation(annotation(member, inItem));
            if (member instanceof FieldMember fieldMember
                && fieldMember.initialValue() != null) {
                field.initializer(literal(fieldMember, javaType, fieldMember.initialValue()));
            }
            builder.addField(field.build());
            if (!options.lombok()) {
                addAccessors(builder, javaType, member.name());
            }
            if (member instanceof FieldMember fieldMember) {
                for (ConditionMember condition : fieldMember.conditions()) {
                    addCondition(builder, fieldMember, javaType, condition);
                }
            }
        }
        if (type.continuable() != null) {
            ClassName handler = handler(type.continuable(), options.packageName());
            builder.addSuperinterface(Continuable.class).addMethod(MethodSpec
                .methodBuilder("hasContinuation")
                .addJavadoc("Calls {@code $L.hasContinuation(this)}.\n", handler.simpleName())
                .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                .returns(TypeName.BOOLEAN)
                .addStatement("return $T.hasContinuation(this)", handler).build());
        }
        if (type.validatable() != null) {
            ClassName handler = handler(type.validatable(), options.packageName());
            builder.addSuperinterface(Validatable.class).addMethod(MethodSpec
                .methodBuilder("validate")
                .addJavadoc("Calls {@code $L.validate(this)}.\n", handler.simpleName())
                .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                .addStatement("$T.validate(this)", handler).build());
        }
        return builder.build();
    }

    /** Gives a value of a field as a Java expression. */
    private static CodeBlock literal(FieldMember field, TypeName javaType, String value) {
        return switch (field.javaType()) {
            case STRING -> CodeBlock.of("$S", value);
            case INT -> CodeBlock.of("$L", value);
            case LONG -> CodeBlock.of("$LL", value);
            case BIG_DECIMAL -> CodeBlock.of("new $T($S)", BigDecimal.class, value);
            case ENUM -> CodeBlock.of("$T.$N", javaType, value);
            // Only a model JSON can give this: the mapper ignores the VALUE of a date field.
            case LOCAL_DATE, LOCAL_TIME, LOCAL_DATE_TIME -> CodeBlock.of("$T.parse($S)", javaType,
                value);
        };
    }

    /**
     * Adds the constant and the boolean method of one level 88 item. The constant holds the
     * first value. The method tests all values and ranges.
     */
    private static void addCondition(TypeSpec.Builder builder, FieldMember field,
                                     TypeName javaType, ConditionMember condition) {
        builder.addField(FieldSpec.builder(javaType, condition.constant(), Modifier.PUBLIC,
                Modifier.STATIC, Modifier.FINAL)
            .addJavadoc("The first value of {@code $L}.\n", condition.cobolName())
            .initializer(literal(field, javaType, condition.values().get(0).from()))
            .build());
        boolean object = field.javaType() == JavaType.STRING
            || field.javaType() == JavaType.BIG_DECIMAL;
        List<CodeBlock> tests = new ArrayList<>();
        for (ValueRange range : condition.values()) {
            CodeBlock from = literal(field, javaType, range.from());
            if (range.thru() == null) {
                tests.add(switch (field.javaType()) {
                    case STRING -> CodeBlock.of("$L.equals($N)", from, field.name());
                    case BIG_DECIMAL -> CodeBlock.of("$N.compareTo($L) == 0", field.name(),
                        from);
                    default -> CodeBlock.of("$N == $L", field.name(), from);
                });
            } else {
                CodeBlock thru = literal(field, javaType, range.thru());
                tests.add(object
                    ? CodeBlock.of("$N.compareTo($L) >= 0 && $N.compareTo($L) <= 0",
                        field.name(), from, field.name(), thru)
                    : CodeBlock.of("$N >= $L && $N <= $L", field.name(), from, field.name(),
                        thru));
            }
        }
        CodeBlock any = CodeBlock.join(tests.stream()
            .map(test -> tests.size() == 1 ? test : CodeBlock.of("($L)", test)).toList(),
            " || ");
        builder.addMethod(MethodSpec.methodBuilder(condition.method())
            .addJavadoc("Tells if {@code $N} holds a value of {@code $L}.\n\n"
                + "@return {@code true} for a value of the level 88 item\n", field.name(),
                condition.cobolName())
            .addModifiers(Modifier.PUBLIC).returns(TypeName.BOOLEAN)
            .addStatement(object ? "return $N != null && ($L)" : "return $L",
                object ? new Object[] {field.name(), any} : new Object[] {any})
            .build());
    }

    private static TypeSpec enumType(EnumModel type, String sourceName) {
        TypeSpec.Builder builder = TypeSpec.enumBuilder(type.name())
            .addModifiers(Modifier.PUBLIC)
            .addJavadoc("Generated by the BookMap copybook generator from {@code $L}.\n"
                + "The level 88 items of {@code $L}.\n", sourceName, type.cobolName());
        for (EnumConstant constant : type.constants()) {
            AnnotationSpec.Builder value = AnnotationSpec.builder(CobolValue.class);
            for (ValueRange range : constant.values()) {
                if (range.thru() == null) {
                    value.addMember("value", "$S", range.from());
                } else {
                    value.addMember("ranges", "$L", AnnotationSpec.builder(
                            CobolValue.Range.class)
                        .addMember("from", "$S", range.from())
                        .addMember("thru", "$S", range.thru()).build());
                }
            }
            builder.addEnumConstant(constant.name(), TypeSpec.anonymousClassBuilder("")
                .addJavadoc("{@code $L}\n", constant.cobolName())
                .addAnnotation(value.build()).build());
        }
        return builder.build();
    }

    /** Gives the handler class. A name without a package is in the generated package. */
    private static ClassName handler(String name, String packageName) {
        int dot = name.lastIndexOf('.');
        return dot < 0 ? ClassName.get(packageName, name)
            : ClassName.get(name.substring(0, dot), name.substring(dot + 1));
    }

    private static ClassName lombok(String name) {
        return ClassName.get("lombok", name);
    }

    private static TypeName javaType(MemberModel member, String packageName) {
        return switch (member) {
            case CollectionMember collection -> ParameterizedTypeName.get(
                ClassName.get(List.class), ClassName.get(packageName, collection.itemClass()));
            case FieldMember field -> switch (field.javaType()) {
                case STRING -> ClassName.get(String.class);
                case INT -> TypeName.INT;
                case LONG -> TypeName.LONG;
                case BIG_DECIMAL -> ClassName.get(BigDecimal.class);
                case ENUM -> ClassName.get(packageName, field.enumType());
                case LOCAL_DATE -> ClassName.get(LocalDate.class);
                case LOCAL_TIME -> ClassName.get(LocalTime.class);
                case LOCAL_DATE_TIME -> ClassName.get(LocalDateTime.class);
            };
        };
    }

    private static AnnotationSpec annotation(MemberModel member, boolean inItem) {
        return switch (member) {
            case FieldMember field -> {
                AnnotationSpec.Builder spec = AnnotationSpec.builder(BookField.class)
                    .addMember("order", "$L", field.order())
                    .addMember("pic", "$S", field.pic());
                if (!inItem && field.direction() != Direction.INPUT_OUTPUT) {
                    spec.addMember("direction", direction(field.direction()));
                }
                if (field.pattern() != null) {
                    spec.addMember("pattern", "$S", field.pattern());
                }
                yield spec.build();
            }
            case CollectionMember collection -> {
                AnnotationSpec.Builder spec = AnnotationSpec.builder(BookCollection.class)
                    .addMember("order", "$L", collection.order())
                    .addMember("maxOccurs", "$L", collection.maxOccurs());
                // A collection in an item class gets the direction of the outer collection.
                if (!inItem) {
                    spec.addMember("direction", direction(collection.direction()));
                }
                if (collection.fixed()) {
                    spec.addMember("fixed", "true");
                }
                if (collection.dependsOn() != null) {
                    spec.addMember("dependsOn", "$S", collection.dependsOn());
                }
                if (collection.emptyKey() != null) {
                    spec.addMember("emptyKey", "$S", collection.emptyKey());
                }
                if (collection.emptyItem() != EmptyItem.LOW_VALUES) {
                    spec.addMember("emptyItem", "$T.$L", EmptyItem.class,
                        collection.emptyItem().name());
                }
                yield spec.build();
            }
        };
    }

    private static CodeBlock direction(Direction direction) {
        return CodeBlock.of("$T.$L", Direction.class, direction.name());
    }

    private static void addAccessors(TypeSpec.Builder builder, TypeName javaType, String name) {
        String suffix = Character.toUpperCase(name.charAt(0)) + name.substring(1);
        builder.addMethod(MethodSpec.methodBuilder("get" + suffix)
            .addModifiers(Modifier.PUBLIC).returns(javaType)
            .addStatement("return $N", name).build());
        builder.addMethod(MethodSpec.methodBuilder("set" + suffix)
            .addModifiers(Modifier.PUBLIC).addParameter(javaType, name)
            .addStatement("this.$N = $N", name, name).build());
    }

    /**
     * Gives the Javadoc of a field: its COBOL declaration. A picture such as {@code **}{@code /99}
     * has the characters that end a comment. Then the Javadoc uses HTML, with {@code /} as
     * {@code &#47;}.
     */
    static CodeBlock declaration(String declaration) {
        if (!declaration.contains("*/")) {
            return CodeBlock.of("{@code $L}\n", declaration);
        }
        String html = declaration.replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace("/", "&#47;").replace("@", "&#64;");
        return CodeBlock.of("<code>$L</code>\n", html);
    }
}
